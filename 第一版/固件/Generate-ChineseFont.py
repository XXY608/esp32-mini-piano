"""Regenerate the TFT UI/GB2312 song-title font from GNU Unifont 17.0.03 (OFL-1.1)."""
import argparse
import gzip
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent
parser = argparse.ArgumentParser()
parser.add_argument("--font", type=Path, required=True, help="unifont-17.0.03.hex.gz")
args = parser.parse_args()
labels = "".join((ROOT / "Board2_1Piano" / name).read_text(encoding="utf-8-sig") for name in ("DisplayText.h", "MenuScreen.h", "ScoreScreen.h", "App.cpp", "BuiltinSongs.h"))
required = set(range(32, 127)) | {ord(c) for c in labels if ord(c) > 127}
# Imported song titles need the GB2312 Chinese repertoire as well as UI labels.
for lead in range(0xb0, 0xf8):
    for trail in range(0xa1, 0xff):
        try:
            required.add(ord(bytes((lead, trail)).decode("gb2312")))
        except UnicodeDecodeError:
            pass
glyphs = {}
with gzip.open(args.font, "rt", encoding="ascii") as font:
    for line in font:
        code, bitmap = line.strip().split(":", 1)
        cp = int(code, 16)
        if cp in required:
            data = bytes.fromhex(bitmap)
            if len(data) not in (16, 32):
                raise ValueError(f"Unsupported glyph width: {cp:04X}")
            glyphs[cp] = data
missing = required - glyphs.keys()
if missing:
    raise ValueError(f"Missing glyphs: {sorted(missing)}")
digest = hashlib.sha256(args.font.read_bytes()).hexdigest()
header = [
    "#pragma once", "#include <stdint.h>", "namespace lcd {",
    "// Generated by Generate-ChineseFont.py; GNU Unifont 17.0.03 subset.",
    "// Copyright (C) 1998-2025 Roman Czyborra, Paul Hardy, Qianqian Fang,",
    "// Andrew Miller, Johnnie Weaver, David Corbett, and other Unifont contributors.",
    "// SIL Open Font License 1.1: fonts/OFL-1.1.txt; see fonts/LICENSE.txt.",
    "// Source: https://unifoundry.com/pub/unifont/unifont-17.0.03/font-builds/unifont-17.0.03.hex.gz",
    f"// Compressed source SHA256: {digest}",
    "struct Glyph { uint16_t codepoint; uint8_t width; uint8_t bitmap[32]; };",
    "static const Glyph kGlyphs[] = {",
]
for cp, data in sorted(glyphs.items()):
    encoded = ",".join(f"0x{b:02x}" for b in data)
    header.append(f"  {{0x{cp:04x}, {len(data) // 2}, {{{encoded}}}}},")
header += ["};", "}", ""]
(ROOT / "Board2_1Piano" / "ChineseFont.h").write_text("\n".join(header), encoding="utf-8")
print(f"Generated {len(glyphs)} glyphs, {sum(len(d) for d in glyphs.values())} bitmap bytes")
