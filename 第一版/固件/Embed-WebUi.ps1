$ErrorActionPreference = 'Stop'
$sketch = Join-Path $PSScriptRoot 'Board2_1Piano'
$html = Get-Content -LiteralPath (Join-Path $sketch 'web\index.html') -Raw -Encoding UTF8
$parser = Get-Content -LiteralPath (Join-Path $sketch 'web\score-parser.js') -Raw -Encoding UTF8
$html = $html.Replace('/* SCORE_PARSER */', $parser)
if ($html.Contains(')PIANOUI"')) { throw 'Raw string delimiter collision' }
$header = "#pragma once`n#include <Arduino.h>`n// Generated by Embed-WebUi.ps1 from web/.`nstatic const char kWebUi[] PROGMEM = R`"PIANOUI($html)PIANOUI`";`n"
[IO.File]::WriteAllText((Join-Path $sketch 'WebUi.h'), $header, [Text.UTF8Encoding]::new($false))
